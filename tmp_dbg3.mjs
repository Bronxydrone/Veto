import { readFileSync } from "node:fs";
import { loadPolicy } from "./src/core/policy.ts";
import { VetoGuard } from "./src/core/service.ts";
const doc = structuredClone(loadPolicy(readFileSync("examples/policy.yaml","utf8")).doc); doc.risk = {};
const PRICES = { NEAR: 2_450_000n, USDC: 1_000_000n };
const clock = { t: Date.parse("2026-11-02T12:00:00Z") };
const g = VetoGuard.create({ policyText: JSON.stringify(doc), clock: () => clock.t, prices: PRICES });
const r1 = await g.submit({id:"a",kind:"ft.transfer",actor:"argo.near",asset:"NEAR",amount:"1.25",to:"compute.near"});
console.log("r1", r1.decision.evaluatedAt, r1.decision.verdict);
clock.t += 86_400_000;
console.log("clock now", new Date(clock.t).toISOString());
const r2 = await g.submit({id:"b",kind:"ft.transfer",actor:"argo.near",asset:"NEAR",amount:"1.25",to:"compute.near"});
console.log("r2", r2.decision.evaluatedAt, r2.decision.verdict, JSON.stringify(r2.decision.limits.daily), r2.decision.reasons.map(x=>x.code).join(","));
const snap = g.snapshot();
console.log("ledger", JSON.stringify(snap.ledger.map(r=>({id:r.actionId, at:new Date(r.at).toISOString(), status:r.status}))));
